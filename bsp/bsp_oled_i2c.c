#include "bsp_oled_i2c.h"
#include "i2c.h"
#include <string.h>
#define OLED_ADDR   0x78U
#define OLED_WIDTH  128
#define OLED_PAGES  8

static uint8_t oled_buf[OLED_PAGES][OLED_WIDTH];

/* ------------------------- 底层 I2C 写入 ------------------------- */
static void oled_write_cmd(uint8_t cmd)
{
    uint8_t buf[2] = {0x00, cmd};
    HAL_I2C_Master_Transmit(&hi2c2, OLED_ADDR, buf, 2, 100);
}

static void oled_write_data_burst(const uint8_t *data, uint16_t len)
{
    uint8_t buf[OLED_WIDTH + 1];
    buf[0] = 0x40;   /* 数据控制字 */
    memcpy(&buf[1], data, len);
    HAL_I2C_Master_Transmit(&hi2c2, OLED_ADDR, buf, len + 1, 100);
}

